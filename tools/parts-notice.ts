interface Row {
  file: string;
  part: Part;
}

export function buildNotice(): string {
  const rows: Row[] = [];
  const dir = resolve(ROOT, 'library');
  for (const name of readdirSync(dir).sort()) {
    if (!/^parts.*\.yaml$/.test(name)) continue;
    const lib = parseLibrary(readFileSync(resolve(dir, name), 'utf8'));
    for (const part of lib.parts) if (part.model) rows.push({ file: part.model.uri, part });
  }
  rows.sort((a, b) => a.file.localeCompare(b.file));

  const used = [...new Set(rows.map((r) => r.part.model!.license!))].sort();
  const unknown = used.filter((l) => !LICENSES[l]);
  if (unknown.length > 0) throw new Error(`no licence text in tools/parts-notice.ts for: ${unknown.join(', ')}`);

  const lines: string[] = [];
  lines.push('# Licences of the bundled part models');
  lines.push('');
  lines.push('Generated by `tools/parts-notice.ts` from `library/parts*.yaml`. Do not edit by hand.');
  lines.push('');
  lines.push(
    `The ${rows.length} GLB files in this folder are 3D models of real products, converted from files their makers published. ` +
      'Each is a separate work under its own licence, listed here. The code of this project is licensed separately (Apache-2.0, see `LICENSE` in the repository root). ' +
      'Product names are used only to identify the parts; this project is not affiliated with or endorsed by their makers.',
  );
  lines.push('');
  for (const id of used) {
    lines.push(`## ${LICENSES[id]!.title} (${id})`);
    lines.push('');
    lines.push(LICENSES[id]!.body);
    lines.push('');
    lines.push('| File | Part | Credit | Original | Changes |');
    lines.push('|---|---|---|---|---|');
    for (const { file, part } of rows.filter((r) => r.part.model!.license === id)) {
      const m = part.model!;
      lines.push(`| \`${file}\` | ${part.name} | ${m.attribution} | ${m.source} | ${m.changes ?? 'Converted to GLB.'} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

const text = buildNotice();
if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== text) {
    console.error('public/parts/NOTICE.md is out of date. Run `npx tsx tools/parts-notice.ts`.');
    process.exit(1);
  }
  console.log('public/parts/NOTICE.md is up to date.');
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
